"""Extract flat query/body request schemas from ASP.NET controllers + C# models.

Body DTOs are flattened to Postman-style Key/Type parameters (top-level properties only).
Nested complex properties are emitted as type \"string\" so they still appear as params.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ONLINE_ROOT = Path(r"C:\Work\Sasfin.Wealth.Online.Api")
DYN_ROOT = Path(r"C:\Work\Sasfin.Dynamics.Api")
WEALTH_ROOT = Path(r"C:\Work\Sasfin.Wealth.Api")
OUT = Path(r"C:\Work\BotFlow\scripts\request-schemas.json")

PROP_RE = re.compile(
    r"public\s+(?:required\s+)?(?:virtual\s+)?"
    r"(?P<type>[\w\.<>\?\[\]]+)\s+(?P<name>\w+)\s*\{\s*get",
    re.M,
)
# positional record: public record Foo(string A, int B);
RECORD_POS_RE = re.compile(
    r"(?:public|internal)\s+(?:partial\s+)?record\s+(\w+)\s*\(([^)]*)\)\s*;",
    re.M,
)
CLASS_RE = re.compile(
    r"(?:public|internal)\s+(?:partial\s+)?(?:record\s+)?(?:class|struct)\s+(\w+)\b"
)


def csharp_to_json_type(typ: str) -> dict:
    t = typ.strip().rstrip("?").split(".")[-1]
    t = re.sub(r"^Nullable<(.+)>$", r"\1", t)
    if t in ("Guid", "System.Guid"):
        return {"type": "string", "format": "uuid"}
    if t in ("int", "Int32", "long", "Int64", "short", "Int16", "byte"):
        return {"type": "integer"}
    if t in ("decimal", "double", "float", "Single", "Double", "Decimal"):
        return {"type": "number"}
    if t in ("bool", "Boolean"):
        return {"type": "boolean"}
    if t in ("DateTime", "DateTimeOffset", "DateOnly", "TimeOnly"):
        return {"type": "string", "format": "date-time"}
    if t.startswith("List<") or t.startswith("IEnumerable<") or t.startswith("ICollection<") or t.endswith("[]"):
        return {"type": "array", "items": {"type": "string"}}
    if t in ("string", "String"):
        return {"type": "string"}
    # Complex / enum / nested DTO → still a parameter, not nested object schema
    return {"type": "string"}


def should_skip_cs(path: Path) -> bool:
    parts_l = {x.lower() for x in path.parts}
    if "obj" in parts_l or "bin" in parts_l:
        return True
    # NSwag / test clients overwrite real entity models with empty shells
    if any(x.endswith(".test") or x.endswith(".tests") for x in parts_l):
        return True
    if "test" in parts_l or "tests" in parts_l:
        return True
    name = path.name.lower()
    if name in ("client.cs", "openapi.cs"):
        return True
    text_head = ""
    try:
        text_head = path.read_text(encoding="utf-8", errors="ignore")[:400]
    except OSError:
        return True
    if "Generated using the NSwag" in text_head or "<auto-generated>" in text_head:
        return True
    return False


def index_classes(roots: list[Path]) -> dict[str, list[tuple[str, str]]]:
    """Map class name -> list of (prop_name, csharp_type). Prefer richer property sets."""
    index: dict[str, list[tuple[str, str]]] = {}
    for root in roots:
        if not root.exists():
            continue
        for p in root.rglob("*.cs"):
            if should_skip_cs(p):
                continue
            text = p.read_text(encoding="utf-8", errors="ignore")
            for rm in RECORD_POS_RE.finditer(text):
                name = rm.group(1)
                props: list[tuple[str, str]] = []
                for part in split_params(rm.group(2)):
                    part = re.sub(r"\[[^\]]*\]", "", part).strip()
                    m = re.match(r"([\w\.<>\?\[\]]+)\s+(\w+)$", part)
                    if m:
                        props.append((m.group(2), m.group(1)))
                if props and len(props) >= len(index.get(name) or []):
                    index[name] = props
            for cm in CLASS_RE.finditer(text):
                name = cm.group(1)
                start = cm.end()
                nxt = CLASS_RE.search(text, start)
                body = text[start : nxt.start() if nxt else len(text)]
                # Limit to first type body brace roughly (avoid scanning whole file)
                brace = body.find("{")
                if brace >= 0:
                    depth = 0
                    end = brace
                    for i, ch in enumerate(body[brace:], start=brace):
                        if ch == "{":
                            depth += 1
                        elif ch == "}":
                            depth -= 1
                            if depth == 0:
                                end = i
                                break
                    body = body[brace : end + 1]
                props = []
                for pm in PROP_RE.finditer(body):
                    typ, pname = pm.group("type"), pm.group("name")
                    if pname in ("get", "set", "value"):
                        continue
                    props.append((pname, typ))
                if props and len(props) >= len(index.get(name) or []):
                    index[name] = props
    return index


def find_controller_meta(text: str) -> tuple[str | None, str, str] | None:
    ctrl_m = re.search(r"public\s+(?:partial\s+)?class\s+(\w+)Controller\b", text)
    if not ctrl_m:
        return None
    controller = ctrl_m.group(1)
    before = text[: ctrl_m.start()]
    chunk = before[-1200:] if len(before) > 1200 else before
    area_m = re.search(r"\[Area\(AreaName\.(\w+)\)\]", chunk)
    area = area_m.group(1) if area_m else None
    route_m = re.search(r'\[Route\("((?:\\.|[^"\\])*)"\)\]', chunk)
    route = route_m.group(1) if route_m else "[controller]/[action]"
    return area, route, controller


def split_params(params: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    cur: list[str] = []
    for ch in params:
        if ch == "<":
            depth += 1
            cur.append(ch)
        elif ch == ">":
            depth = max(0, depth - 1)
            cur.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if cur:
        parts.append("".join(cur).strip())
    return [p for p in parts if p]


PRIMITIVES = {
    "string",
    "Guid",
    "int",
    "Int32",
    "long",
    "Int64",
    "bool",
    "Boolean",
    "decimal",
    "double",
    "float",
    "DateTime",
    "DateTimeOffset",
    "DateOnly",
    "short",
    "Int16",
    "byte",
    "Single",
    "Double",
    "Decimal",
}


def classify_param(part: str) -> tuple[str, str, str] | None:
    """Return (kind, csharp_type, name) where kind is query|body|skip."""
    raw = part.strip()
    if not raw or "CancellationToken" in raw:
        return None
    is_body = "[FromBody]" in raw or "FromBody" in raw
    is_form = "[FromForm]" in raw or "FromForm" in raw
    is_query = "[FromQuery]" in raw or "FromQuery" in raw
    cleaned = re.sub(r"\[[^\]]*\]", "", raw).strip()
    m = re.match(
        r"(?:required\s+)?([\w\.<>\?\[\]]+)\s+(\w+)(?:\s*=\s*.+)?$",
        cleaned,
    )
    if not m:
        return None
    typ, name = m.group(1), m.group(2)
    base = typ.rstrip("?").split(".")[-1]
    if is_form:
        return ("body", typ, name)  # flatten form fields if DTO
    if is_body:
        return ("body", typ, name)
    if is_query:
        return ("query", typ, name)
    # Convention: complex type on POST → body; primitive → query
    if base not in PRIMITIVES and "Enum" not in base:
        return ("body", typ, name)
    return ("query", typ, name)


def props_from_type(
    typ: str, class_index: dict[str, list[tuple[str, str]]]
) -> dict[str, dict] | None:
    base = typ.rstrip("?").split(".")[-1]
    if base in PRIMITIVES or "Enum" in base:
        return None
    props = class_index.get(base)
    if not props:
        return None
    out: dict[str, dict] = {}
    for pname, ptyp in props:
        out[pname] = csharp_to_json_type(ptyp)
    return out or None


def parse_controllers(
    controllers_root: Path, class_index: dict[str, list[tuple[str, str]]]
) -> dict[str, dict]:
    """Key: Controller_Action → { query, body, method }"""
    result: dict[str, dict] = {}
    if not controllers_root.exists():
        return result
    for p in controllers_root.rglob("*Controller.cs"):
        text = p.read_text(encoding="utf-8", errors="ignore")
        meta = find_controller_meta(text)
        if not meta:
            continue
        _area, _route, controller = meta
        http_re = re.compile(
            r"\[Http(Get|Post|Put|Delete|Patch)(?:\(\"((?:\\.|[^\"\\])*)\"\))?\]",
            re.M,
        )
        method_re = re.compile(
            r"public\s+(?:async\s+)?(?:[\w.<>,\[\]\s\?]+?)\s+(\w+)\s*\(",
            re.M,
        )
        for hm in http_re.finditer(text):
            method = hm.group(1).upper()
            after = text[hm.end() : hm.end() + 900]
            mm = method_re.search(after)
            if not mm:
                continue
            action = mm.group(1)
            if action == controller:
                continue
            # Balanced param list — expression-bodied methods have ") =>" and nested "()"
            params_start = mm.end()
            depth = 1
            i = params_start
            while i < len(after) and depth > 0:
                ch = after[i]
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                i += 1
            if depth != 0:
                continue
            params = " ".join(after[params_start : i - 1].split())
            query_props: dict[str, dict] = {}
            body_props: dict[str, dict] = {}
            for part in split_params(params):
                classified = classify_param(part)
                if not classified:
                    continue
                kind, typ, name = classified
                if kind == "query":
                    base = typ.rstrip("?").split(".")[-1]
                    if base in PRIMITIVES or "Enum" in base:
                        query_props[name] = csharp_to_json_type(typ)
                    else:
                        # [FromQuery] complex filter → flatten into query params
                        nested = props_from_type(typ, class_index)
                        if nested:
                            query_props.update(nested)
                        else:
                            query_props[name] = {"type": "string"}
                else:
                    nested = props_from_type(typ, class_index)
                    if nested:
                        body_props.update(nested)
                    else:
                        # Primitive FromBody (rare) or unknown DTO
                        base = typ.rstrip("?").split(".")[-1]
                        if base in PRIMITIVES:
                            body_props[name] = csharp_to_json_type(typ)
                        else:
                            # Unknown DTO: keep a single string param named after the type
                            body_props[name] = {"type": "string"}
            key = f"{controller}_{action}"
            result[key] = {
                "controller": controller,
                "action": action,
                "method": method,
                "query": query_props,
                "body": body_props,
            }
    return result


def main() -> None:
    online_classes = index_classes([ONLINE_ROOT])
    dyn_classes = index_classes([DYN_ROOT])
    wealth_classes = index_classes([WEALTH_ROOT])

    online = parse_controllers(
        ONLINE_ROOT / "Sasfin.Wealth.Online.Api" / "Controllers",
        online_classes,
    )
    dynamics = parse_controllers(
        DYN_ROOT / "Sasfin.Dynamics.Api" / "Controllers",
        dyn_classes,
    )
    wealth_ctrl = WEALTH_ROOT / "Wealth.Api" / "Controllers"
    if not wealth_ctrl.exists():
        wealth_ctrl = WEALTH_ROOT / "Sasfin.Wealth.Api" / "Controllers"
    wealth = parse_controllers(wealth_ctrl, wealth_classes)

    payload = {
        "wealth": wealth,
        "wealthOnline": online,
        "dynamics": dynamics,
        "stats": {
            "wealth": len(wealth),
            "wealthOnline": len(online),
            "dynamics": len(dynamics),
            "onlineClasses": len(online_classes),
            "dynClasses": len(dyn_classes),
            "wealthClasses": len(wealth_classes),
            "onlineWithBody": sum(1 for v in online.values() if v.get("body")),
            "dynWithBody": sum(1 for v in dynamics.values() if v.get("body")),
            "wealthWithBody": sum(1 for v in wealth.values() if v.get("body")),
        },
    }
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(json.dumps(payload["stats"], indent=2))
    # samples
    for name, bag in (("online", online), ("dyn", dynamics), ("wealth", wealth)):
        sample = next((v for v in bag.values() if v.get("body")), None)
        print(name, "sample body", sample["controller"] if sample else None, sample.get("body") if sample else None)


if __name__ == "__main__":
    main()
