"""Generate server/src/apis/requestSchemas.generated.ts from request-schemas.json.

Run after extract-request-schemas.py. No hand-maintained endpoint params.
"""
from __future__ import annotations

import json
from pathlib import Path

SRC = Path(r"C:\Work\BotFlow\scripts\request-schemas.json")
OUT = Path(r"C:\Work\BotFlow\server\src\apis\requestSchemas.generated.ts")


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    # Drop stats from runtime payload
    payload = {
        "wealth": data.get("wealth") or {},
        "wealthOnline": data.get("wealthOnline") or {},
        "dynamics": data.get("dynamics") or {},
    }
    body = (
        "/** AUTO-GENERATED by scripts/generate-request-schemas-ts.py — do not edit. */\n"
        "import type { ExtractedRequestSchemaMap } from \"./requestSchemas.js\";\n\n"
        "export const EXTRACTED_REQUEST_SCHEMAS: ExtractedRequestSchemaMap = "
        + json.dumps(payload, indent=2)
        + " as ExtractedRequestSchemaMap;\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(
        f"Wrote {OUT} "
        f"(wealth={len(payload['wealth'])}, "
        f"online={len(payload['wealthOnline'])}, "
        f"dynamics={len(payload['dynamics'])})"
    )


if __name__ == "__main__":
    main()
