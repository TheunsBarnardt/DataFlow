export interface OnlineEndpointDef {
  controller: string;
  action: string;
  method: ApiHttpMethod;
  auth: ApiAuthMode;
  summary: string;
  /** Explicit route path (area/controller/action + suffixes). */
  path: string;
  area?: string;
  impl?: "login" | "refresh" | "proxy" | "dynamicsHttp" | "mssql";
  requestQuerySchema?: JsonSchema;
  requestBodySchema?: JsonSchema;
  responseSchema?: JsonSchema;
}

function ep(
  controller: string,
  action: string,
  method: ApiHttpMethod,
  auth: ApiAuthMode,
  summary: string,
  extra: Partial<OnlineEndpointDef> & { path: string },
): OnlineEndpointDef {
  return {
    controller,
    action,
    method,
    auth,
    summary,
    impl: "proxy",
    ...extra,
  };
}

