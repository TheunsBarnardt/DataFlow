/** Whether this node type is a workflow trigger. */
export function isTriggerType(type: string): boolean {
  return TRIGGER_TYPES.has(type);
}

/** Lucide icon component for a workflow node type. */
export function getNodeIcon(type: string): LucideIcon {
  return ICON_BY_TYPE[type] ?? Circle;
}

/** CSS color string for a workflow node type accent. */
export function getNodeColor(type: string): string {
  if (COLOR_BY_TYPE[type]) return COLOR_BY_TYPE[type];
  if (TRIGGER_TYPES.has(type)) return "var(--brand)";
  if (
    type.startsWith("http") ||
    type.includes("Api") ||
    type === "graphql" ||
    type === "jwt"
  ) {
    return "#3b82f6";
  }
  if (type === "if" || type === "switch" || type === "filter") return "#f97316";
  return "#6b7280";
}
